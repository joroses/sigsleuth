#!/usr/bin/env bash
# Write the API's response types for the frontend from the backend's OpenAPI
# schema, so the Python response classes are the only hand-written contract.
# Run it after changing a response class; --check (verify.sh) fails when the
# saved file is out of date instead of writing it.
set -euo pipefail

project_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$project_root"

target=src/frontend/src/app/api.generated.ts
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

# Every response field is always sent, so mark each one required: a field
# with a default would otherwise come out optional. Field titles only repeat
# the field name, so drop them.
uv run --locked python -c '
import json, sys
from sigsleuth.api import create_app
from sigsleuth.config import Settings
schema = create_app(Settings("unused.db")).openapi()
for component in schema["components"]["schemas"].values():
    if "properties" in component:
        component["required"] = list(component["properties"])
        for field in component["properties"].values():
            field.pop("title", None)
json.dump(schema, sys.stdout)
' >"$work/openapi.json"

(
  cd src/frontend
  corepack pnpm exec openapi-typescript "$work/openapi.json" --output "$work/api.generated.ts" >/dev/null
  { echo "// Generated by scripts/api-types.sh from the backend's response classes; do not edit."; cat "$work/api.generated.ts"; } >"$work/out.ts"
  corepack pnpm exec prettier --stdin-filepath "$target" <"$work/out.ts" >"$work/formatted.ts"
)

if [[ "${1:-}" == "--check" ]]; then
  cmp -s "$work/formatted.ts" "$target" || {
    echo "$target is out of date with the backend's response classes. Run ./scripts/api-types.sh." >&2
    exit 1
  }
else
  cp "$work/formatted.ts" "$target"
fi
